const { chromium } = require('playwright-core')
const URL = process.env.PARK_URL || 'http://localhost:3001'
;(async () => {
  const b = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await b.newPage({ viewport: { width: 1280, height: 720 } })
  const errs=[]; page.on('pageerror',e=>errs.push(e.message))
  await page.goto(URL, { waitUntil: 'load', timeout: 180000 })
  await page.waitForFunction(() => !!window.__park, null, { timeout: 180000 })
  await page.waitForTimeout(4500)
  const enter = page.locator('text=Enter the Park'); if (await enter.count()) await enter.click()
  await page.evaluate(() => window.__park.store.getState().setTimeMode('day'))
  // stand just in front of the ring-toss stall (25,27) and face it (first person)
  await page.evaluate(() => window.__park.rig.body.setTranslation({ x: 23.6, y: 1.5, z: 25.6 }, true))
  await page.evaluate(() => { window.__park.look.yaw = -2.4; window.__park.look.pitch = -0.12 })
  await page.waitForTimeout(1500)
  await page.screenshot({ path: 'scripts/shot-bottles.png' })
  console.log('errors:', errs.length?errs.join(' | '):'(none)')
  await b.close()
})().catch(e=>{console.error('FAIL',e.message);process.exit(1)})
